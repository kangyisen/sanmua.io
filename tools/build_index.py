def _png_size(data):
    if data[:8] != b"\x89PNG\r\n\x1a\n" or len(data) < 24:
        return None
    return struct.unpack(">II", data[16:24])


def _gif_size(data):
    if data[:6] not in (b"GIF87a", b"GIF89a") or len(data) < 10:
        return None
    return struct.unpack("<HH", data[6:10])


def _jpeg_size(data):
    if data[:2] != b"\xff\xd8":
        return None
    i = 2
    while i + 9 < len(data):
        if data[i] != 0xFF:
            i += 1
            continue
        marker = data[i + 1]
        if marker in (0xD8, 0x01) or 0xD0 <= marker <= 0xD7:
            i += 2
            continue
        if 0xC0 <= marker <= 0xCF and marker not in (0xC4, 0xC8, 0xCC):
            height, width = struct.unpack(">HH", data[i + 5:i + 9])
            return width, height
        length = struct.unpack(">H", data[i + 2:i + 4])[0]
        if length < 2:
            return None
        i += 2 + length
    return None


def _webp_size(data):
    if data[:4] != b"RIFF" or data[8:12] != b"WEBP" or len(data) < 30:
        return None
    fmt = data[12:16]
    if fmt == b"VP8 ":
        return (struct.unpack("<H", data[26:28])[0] & 0x3FFF,
                struct.unpack("<H", data[28:30])[0] & 0x3FFF)
    if fmt == b"VP8L":
        bits = struct.unpack("<I", data[21:25])[0]
        return (bits & 0x3FFF) + 1, ((bits >> 14) & 0x3FFF) + 1
    if fmt == b"VP8X":
        return (int.from_bytes(data[24:27], "little") + 1,
                int.from_bytes(data[27:30], "little") + 1)
    return None


def _svg_size(data):
    head = data[:1024].decode("utf-8", "ignore")
    m = re.search(r"<svg[^>]*>", head, re.I)
    if not m:
        return None
    tag = m.group(0)

    def attr(name):
        am = re.search(name + r"\s*=\s*[\"']([^\"']+)[\"']", tag, re.I)
        return am.group(1).strip() if am else None

    try:
        width, height = attr("width"), attr("height")
        if width and height and "%" not in width and "%" not in height:
            width = width.removesuffix("px")
            height = height.removesuffix("px")
            if float(width) > 0 and float(height) > 0:
                return round(float(width)), round(float(height))
        view_box = attr("viewBox")
        if view_box:
            parts = view_box.replace(",", " ").split()
            if len(parts) == 4 and float(parts[2]) > 0 and float(parts[3]) > 0:
                return round(float(parts[2])), round(float(parts[3]))
    except ValueError:
        pass
    return None


def local_image_size(url):
    """读取站内图片的固有尺寸，给 <img> 写死 width/height（避免加载时布局抖动）。"""
    path = urlsplit(url).path
    if not path or path.startswith("//"):
        return None
    if path.startswith("/"):
        fs_path = os.path.join(ROOT, path.lstrip("/").replace("/", os.sep))
    else:
        fs_path = os.path.join(POSTS_DIR, path.replace("/", os.sep))
    try:
        with io.open(fs_path, "rb") as f:
            data = f.read(1 << 20)
    except OSError:
        return None
    if b"<svg" in data[:512]:
        return _svg_size(data)
    for probe in (_png_size, _gif_size, _jpeg_size, _webp_size):
        size = probe(data)
        if size:
            return size
    return None


class _Inline:
    """行内 Markdown 渲染：`code`、图片、链接、**加粗**、*斜体*。"""

    CODE_RE = re.compile(r"`([^`\n]+)`")
    LINK_RE = re.compile(r"!?\[([^\]]*)\]\(([^)\s]+)(?:\s+&quot;[^&]*&quot;)?\)")
    BOLD_RE = re.compile(r"\*\*(?=\S)(.+?)(?<=\S)\*\*")
    ITALIC_RE = re.compile(r"\*(?=\S)([^*\n]+?)(?<=\S)\*")

    def __init__(self):
        self.protected = []

    def _protect(self, html):
        self.protected.append(html)
        return "\x00%d\x00" % (len(self.protected) - 1)

    def render(self, text):
        def code_repl(m):
            return self._protect("<code>%s</code>" % esc(m.group(1)))

        text = self.CODE_RE.sub(code_repl, text)
        text = esc(text)

        def link_repl(m):
            whole, alt, url = m.group(0), m.group(1), m.group(2)
            # The input was escaped above; decode attributes once before escaping
            # them for HTML so query strings keep their original ampersands.
            url = html_mod.unescape(url)
            if whole.startswith("!"):
                size = local_image_size(url)
                dims = ' width="%d" height="%d"' % size if size else ""
                return self._protect(
                    '<img src="%s" alt="%s" loading="lazy" decoding="async"%s />'
                    % (esc_attr(url), esc_attr(html_mod.unescape(alt)), dims)
                )
            scheme = urlsplit(url).scheme.lower()
            if scheme in ("javascript", "vbscript", "data"):
                # 脚本伪协议一律退化为纯文本，杜绝正文里的存储型 XSS。
                return alt
            attrs = ""
            if scheme in ("http", "https") and not url.startswith(BASE_URL):
                attrs = ' target="_blank" rel="noopener noreferrer"'
            return self._protect('<a href="%s"%s>%s</a>' % (esc_attr(url), attrs, alt))

        text = self.LINK_RE.sub(link_repl, text)
        text = self.BOLD_RE.sub(r"<strong>\1</strong>", text)
        text = self.ITALIC_RE.sub(r"<em>\1</em>", text)

        def restore(m):
            return self.protected[int(m.group(1))]

        return re.sub("\x00(\\d+)\x00", restore, text)


def render_inline(text):
    return _Inline().render(text)


_FENCE_RE = re.compile(r"^\s*```")
_HEADING_RE = re.compile(r"^(#{1,6})\s+(.*?)\s*#*\s*$")
_HR_RE = re.compile(r"^ {0,3}([-*_])(?:\s*\1){2,}\s*$")
_QUOTE_RE = re.compile(r"^\s*>")
_LIST_RE = re.compile(r"^(\s*)([-*+]|\d+[.)])\s+(.*)$")
_TABLE_SEP_RE = re.compile(r"^\s*\|?\s*:?-{3,}:?\s*(\|\s*:?-{3,}:?\s*)*\|?\s*$")


def _split_row(line):
    line = line.strip()
    if line.startswith("|"):
        line = line[1:]
    if line.endswith("|"):
        line = line[:-1]
    return [c.strip() for c in line.split("|")]


def _indent_width(line):
    return len(line) - len(line.lstrip())


def md_to_html(md_text):
    """把 Markdown 正文渲染成 HTML。覆盖 GFM 常用子集：
    标题、段落、加粗、斜体、行内代码、链接、图片、围栏代码块、
    有序/无序列表（含一层嵌套）、引用、表格、分割线。
    """
    lines = md_text.replace("\r\n", "\n").replace("\r", "\n").split("\n")
    out = []
    i, n = 0, len(lines)
    while i < n:
        line = lines[i]
        if not line.strip():
            i += 1
            continue
        # HTML 注释整块跳过
        if line.strip().startswith("<!--"):
            end = line.find("-->")
            while end == -1 and i < n - 1:
                i += 1
                end = lines[i].find("-->")
            i += 1
            continue
        # 围栏代码块
        if _FENCE_RE.match(line):
            lang = line.strip()[3:].strip()
            code = []
            i += 1
            while i < n and not _FENCE_RE.match(lines[i]):
                code.append(lines[i])
                i += 1
            i += 1  # 跳过收尾 ```
            cls = ' class="language-%s"' % esc_attr(lang) if lang else ""
            out.append("<pre><code%s>%s</code></pre>" % (cls, esc("\n".join(code))))
            continue
        m = _HEADING_RE.match(line)
        if m:
            level = len(m.group(1))
            out.append("<h%d>%s</h%d>" % (level, render_inline(m.group(2)), level))
            i += 1
            continue
        if _HR_RE.match(line):
            out.append("<hr />")
            i += 1
            continue
        if _QUOTE_RE.match(line):
            quote = []
            while i < n and _QUOTE_RE.match(lines[i]):
                quote.append(re.sub(r"^\s*>\s?", "", lines[i]))
                i += 1
            out.append("<blockquote>%s</blockquote>" % md_to_html("\n".join(quote)))
            continue
        # 表格：当前行含 | 且下一行是分隔行
        if "|" in line and i + 1 < n and _TABLE_SEP_RE.match(lines[i + 1]):
            headers = _split_row(line)
            i += 2
            rows = []
            while i < n and "|" in lines[i] and lines[i].strip():
                rows.append(_split_row(lines[i]))
                i += 1
            parts = ["<table><thead><tr>"]
            parts += ["<th>%s</th>" % render_inline(c) for c in headers]
            parts.append("</tr></thead><tbody>")
            for row in rows:
                parts.append("<tr>")
                parts += ["<td>%s</td>" % render_inline(c) for c in row]
                parts.append("</tr>")
            parts.append("</tbody></table>")
            out.append("".join(parts))
            continue
        m = _LIST_RE.match(line)
        if m:
            base_indent = _indent_width(line)
            ordered = bool(re.match(r"^\d", m.group(2)))
            items = []
            while i < n:
                line2 = lines[i]
                m2 = _LIST_RE.match(line2)
                if not m2:
                    break
                if _indent_width(line2) != base_indent:
                    break
                if bool(re.match(r"^\d", m2.group(2))) != ordered:
                    break
                items.append([m2.group(3), []])
                i += 1
                # 收集比当前列表项缩进更深的行，作为嵌套内容（子列表 / 代码块 / 续段）
                nested = []
                while i < n:
                    nxt = lines[i]
                    if not nxt.strip():
                        # 空行后如果还是深缩进行，继续属于本项；否则结束
                        j = i + 1
                        while j < n and not lines[j].strip():
                            j += 1
                        if j < n and _indent_width(lines[j]) > base_indent:
                            nested.append("")
                            i = j
                            continue
                        break
                    if _indent_width(nxt) > base_indent:
                        nested.append(nxt[base_indent + 2:] if _indent_width(nxt) >= base_indent + 2 else nxt.lstrip())
                        i += 1
                        continue
                    break
                if nested:
                    block = "\n".join(nested)
                    if _LIST_RE.match(block.lstrip()):
                        items[-1][1].append(md_to_html(block))
                    elif _FENCE_RE.match(block.lstrip()):
                        out_html = md_to_html(block)
                        items[-1][1].append(out_html)
                    else:
                        items[-1][1].append("<p>%s</p>" % render_inline(" ".join(block.split())))
            tag = "ol" if ordered else "ul"
            parts = ["<%s>" % tag]
            for text, extra in items:
                parts.append("<li>%s%s</li>" % (render_inline(text), "".join(extra)))
            parts.append("</%s>" % tag)
            out.append("".join(parts))
            continue
        # 段落：连续收集到空行或下一个块级语法
        para = [line]
        i += 1
        while i < n and lines[i].strip():
            nxt = lines[i]
            if (
                _FENCE_RE.match(nxt)
                or _HEADING_RE.match(nxt)
                or _HR_RE.match(nxt)
                or _QUOTE_RE.match(nxt)
                or _LIST_RE.match(nxt)
            ):
                break
            if "|" in nxt and i + 1 < n and _TABLE_SEP_RE.match(lines[i + 1]):
                break
            para.append(nxt)
            i += 1
        out.append("<p>%s</p>" % render_inline("\n".join(para)))
    return "\n".join(out)


