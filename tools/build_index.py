def strip_quotes(value):
    value = value.strip()
    if len(value) >= 2 and value[0] == value[-1] and value[0] in ("'", '"'):
        value = value[1:-1]
    return value.strip()


def split_tags(raw):
    raw = raw.strip()
    if not raw:
        return []
    if raw.startswith("[") and raw.endswith("]"):
        raw = raw[1:-1]
    parts = re.split(r"[,，]", raw)
    return [p.strip().strip("'\"") for p in parts if p.strip()]


def parse_frontmatter(text):
    """解析顶部 --- ... --- 块，返回 (fields, error)。"""
    if not text.lstrip().startswith("---"):
        return None, "缺少 frontmatter（文件需以 --- 开头）"
    m = re.match(r"^\s*---\s*\n(.*?)\n---\s*(?:\n|$)", text, re.S)
    if not m:
        return None, "frontmatter 没有以第二个 --- 结束"
    block = m.group(1)
    fields = {}
    lines = block.split("\n")
    i = 0
    while i < len(lines):
        line = lines[i]
        if not line.strip():
            i += 1
            continue
        bm = re.match(r"^\s*-\s+(.*)$", line)
        if bm:
            key = fields.get("__last_key__")
            if key:
                fields.setdefault(key, [])
                if isinstance(fields[key], list):
                    fields[key].append(strip_quotes(bm.group(1)))
            i += 1
            continue
        km = re.match(r"^([A-Za-z_][A-Za-z0-9_-]*)\s*:\s*(.*)$", line)
        if not km:
            i += 1
            continue
        key, value = km.group(1), km.group(2)
        fields["__last_key__"] = key
        if key == "tags":
            fields[key] = split_tags(value) if value.strip() else []
        else:
            fields[key] = strip_quotes(value)
        i += 1
    fields.pop("__last_key__", None)
    return fields, None


