def collect_md():
    entries = []
    for name in os.listdir(POSTS_DIR):
        if not name.endswith(".md") or name.startswith("_"):
            # 下划线开头（如 _template.md）为模板/草稿，不纳入索引
            continue
        path = os.path.join(POSTS_DIR, name)
        with io.open(path, encoding="utf-8") as f:
            text = f.read()
        fm, err = parse_frontmatter(text)
        if err:
            print("跳过 %s：%s" % (name, err))
            continue
        missing = [k for k in ("title", "date") if not fm.get(k)]
        if missing:
            print("跳过 %s：frontmatter 缺少字段 %s" % (name, ", ".join(missing)))
            continue
        slug = name[:-3]
        body = text[re.match(r"^\s*---\s*\n.*?\n---\s*(?:\n|$)", text, re.S).end():]
        # 预渲染静态文章页，正文复用给全文索引与阅读时长。
        body_html = md_to_html(body.strip())
        # 首图立即加载并提示高优先级，其余图片保持懒加载。
        if "<img" in body_html:
            body_html = body_html.replace(' loading="lazy"', ' fetchpriority="high"', 1)
        content = strip_html_text(body_html)
        stats = reading_stats(content)
        write_file(
            os.path.join(POSTS_DIR, slug, "index.html"),
            GENERATED_MARK + "\n" + render_post_page(
                fm, body_html, slug, word_count=stats["wordCount"]
            ),
        )
        entries.append({
            "title": fm["title"],
            "href": "/posts/%s/" % slug,
            "date": fm["date"],
            "tags": fm.get("tags", []),
            "category": normalize_category(fm.get("tags", [])),
            "excerpt": fm.get("excerpt", ""),
            "isNew": True,
            "content": content,
            "html": body_html,
            **stats,
        })
    # md 文章：日期降序，同日按文件名降序
    entries.sort(key=lambda e: (e["date"], e["href"]), reverse=True)
    return entries


class _ArticleText(HTMLParser):
    """Extract visible text, preferring the actual article over page metadata."""

    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.all_text = []
        self.article_text = []
        self.hidden = []
        self.capture_tag = None
        self.capture_depth = 0
        self.found_article = False

    def handle_starttag(self, tag, attrs):
        attrs = dict(attrs)
        if tag in ("script", "style", "head", "noscript", "svg"):
            self.hidden.append(tag)
        if self.hidden:
            return
        if self.capture_tag == tag:
            self.capture_depth += 1
        elif not self.capture_tag and not self.found_article and (
            attrs.get("id") == "write"
            or "article-body" in attrs.get("class", "").split()
        ):
            self.capture_tag = tag
            self.capture_depth = 1
            self.found_article = True
        self.handle_data(" ")

    def handle_endtag(self, tag):
        if self.hidden:
            if tag == self.hidden[-1]:
                self.hidden.pop()
            return
        self.handle_data(" ")
        if tag == self.capture_tag:
            self.capture_depth -= 1
            if self.capture_depth == 0:
                self.capture_tag = None

    def handle_data(self, data):
        if not self.hidden:
            self.all_text.append(data)
            if self.capture_tag:
                self.article_text.append(data)


def strip_html_text(raw):
    parser = _ArticleText()
    parser.feed(raw)
    return " ".join("".join(
        parser.article_text if parser.found_article else parser.all_text
    ).split())


def reading_stats(text):
    """Estimate mixed Chinese/English reading time from visible article text."""
    chinese = len(re.findall(r"[\u3400-\u9fff]", text))
    words = len(re.findall(r"[A-Za-z0-9]+(?:['_-][A-Za-z0-9]+)*", text))
    return {
        "wordCount": chinese + words,
        "readingMinutes": max(1, math.ceil(chinese / 350 + words / 200)),
    }


