SEO_START = "<!-- meta: injected by tools/build_index.py (start) -->"
SEO_END = "<!-- meta: injected by tools/build_index.py (end) -->"


def _inject_head_block(html, block, anchor_regex):
    """在 anchor（如 </title>）之后插入块；已注入过则整块替换，保证幂等。"""
    pattern = re.compile(re.escape(SEO_START) + r".*?" + re.escape(SEO_END), re.S)
    if pattern.search(html):
        return pattern.sub(lambda m: SEO_START + block + SEO_END, html, count=1)
    m = re.search(anchor_regex, html, re.I)
    if not m:
        return html
    return html[:m.end()] + "\n    " + SEO_START + block + SEO_END + html[m.end():]


def _seo_block(title, description, canonical, jsonld):
    parts = [
        '<meta name="description" content="%s" />' % esc_attr(description),
        '<link rel="canonical" href="%s" />' % esc_attr(canonical),
        '<meta property="og:site_name" content="%s" />' % esc_attr(SITE_NAME),
        '<meta property="og:title" content="%s" />' % esc_attr(title),
        '<meta property="og:description" content="%s" />' % esc_attr(description),
        '<meta property="og:type" content="article" />',
        '<meta property="og:url" content="%s" />' % esc_attr(canonical),
        '<meta property="og:image" content="%s" />' % esc_attr(BASE_URL + OG_IMAGE),
        '<meta name="twitter:card" content="summary_large_image" />',
        '<link rel="alternate" type="application/rss+xml" title="sanmua" href="/feed.xml" />',
        '<script type="application/ld+json">%s</script>' % jsonld,
    ]
    return "\n    ".join(parts)


def inject_legacy_meta(entries):
    """给手写 HTML 旧文章补齐 description / canonical / OG / JSON-LD。

    旧文章此前只有 <title>，搜索收录与分享卡片基本裸奔；注入块幂等，
    重复构建整块替换。顺带让含代码块的旧文也按需加载 highlight.js。
    """
    changed = []
    for entry in entries:
        href = entry.get("href", "")
        if not href.endswith(".html"):
            continue
        path = os.path.join(ROOT, href.lstrip("/").replace("/", os.sep))
        try:
            with io.open(path, encoding="utf-8") as f:
                html = f.read()
        except OSError:
            continue
        canonical = BASE_URL + href
        block = _seo_block(
            entry.get("title", ""),
            entry.get("excerpt") or SITE_DESC,
            canonical,
            build_jsonld(entry.get("title", ""), entry.get("date", ""),
                         entry.get("excerpt", ""), canonical,
                         tags=entry.get("tags", []), word_count=entry.get("wordCount")),
        )
        updated = _inject_head_block(html, block, r"<title>.*?</title>")
        # 与 md 文章页模板对齐：补 skip-link 与 main 地标（无障碍导航）。
        if '<article class="prose">' in updated and "<main" not in updated:
            updated = updated.replace(
                '<article class="prose">',
                '<a class="skip-link" href="#main">跳到主要内容</a>\n'
                '    <main id="main">\n'
                '      <article class="prose">',
                1,
            )
            idx = updated.rfind("</article>")
            updated = (
                updated[:idx]
                + "</article>\n    </main>"
                + updated[idx + len("</article>"):]
            )
        if "<pre" in updated and "highlight.min.js" not in updated:
            # 旧文此前从未加载过高亮库，补上与 md 文章一致的行为。
            updated = updated.replace(
                "</body>",
                '    <script defer src="/assets/js/highlight.min.js"></script>\n'
                '    <script defer src="/assets/js/highlight-run.js"></script>\n'
                "  </body>",
                1,
            )
        if updated != html:
            write_file(path, updated)
            changed.append(href)
    return changed


def normalize_typora_pages():
    """清理 Typora 导出页：去掉渲染阻塞的 Google Fonts 外链，补 lang / 描述 / canonical。"""
    changed = []
    for page, description in TYPORA_PAGES.items():
        path = os.path.join(ROOT, page.lstrip("/").replace("/", os.sep))
        try:
            with io.open(path, encoding="utf-8") as f:
                html = f.read()
        except OSError:
            continue
        original = html
        # fonts.googleapis.com 在主要读者所在地不可达，且是渲染阻塞资源，直接移除。
        html = re.sub(r"<link\b[^>]*fonts\.googleapis\.com[^>]*>\s*", "", html, flags=re.I)
        if not re.search(r"<html\b[^>]*\blang\s*=", html, re.I):
            html = re.sub(r"<html\b", '<html lang="zh-CN"', html, count=1, flags=re.I)
        block = (
            '<meta name="description" content="%s" />\n    '
            '<link rel="canonical" href="%s" />'
            % (esc_attr(description), esc_attr(BASE_URL + page))
        )
        if SEO_START in html:
            # 页面同时在 posts.legacy.json 里，inject_legacy_meta 已注入
            # 含 OG / JSON-LD 的完整块，这里只做字体与 lang 清理。
            pass
        else:
            html = _inject_head_block(html, block, r"<title>.*?</title>")
        if html != original:
            write_file(path, html)
            changed.append(page)
    return changed


